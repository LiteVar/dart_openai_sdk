import 'package:http/http.dart' as http;

import '../../models/fine_tuning/fine_tuning_checkpoint.dart';
import '../../models/fine_tuning/fine_tuning_event.dart';
import '../../models/fine_tuning/fine_tuning_job.dart';
import '../../models/fine_tuning/fine_tuning_job_list.dart';

/// Fine-tuning API namespace, kept separate from the legacy `fineTune` module.
abstract class OpenAIFineTuningBase {
  OpenAIFineTuningJobsBase get jobs;
}

/// Contract for current fine-tuning job operations.
abstract class OpenAIFineTuningJobsBase {
  String get endpoint;
  OpenAIFineTuningCheckpointsBase get checkpoints;

  Future<OpenAIFineTuningJob> create({
    required String model,
    required String trainingFile,
    String? validationFile,
    String? suffix,
    int? seed,
    Map<String, dynamic>? method,
    Map<String, dynamic>? hyperparameters,
    List<Map<String, dynamic>>? integrations,
    Map<String, dynamic>? metadata,
    http.Client? client,
  });

  Future<OpenAIFineTuningJobList> list({
    String? after,
    int? limit,
    Map<String, String>? metadata,
    bool filterNullMetadata = false,
    http.Client? client,
  });

  Future<OpenAIFineTuningJob> retrieve({
    required String fineTuningJobId,
    http.Client? client,
  });

  Future<OpenAIFineTuningJob> cancel({
    required String fineTuningJobId,
    http.Client? client,
  });

  Future<OpenAIFineTuningJob> pause({
    required String fineTuningJobId,
    http.Client? client,
  });

  Future<OpenAIFineTuningJob> resume({
    required String fineTuningJobId,
    http.Client? client,
  });

  Future<OpenAIFineTuningEventList> listEvents({
    required String fineTuningJobId,
    String? after,
    int? limit,
    http.Client? client,
  });
}

/// Contract for checkpoints generated by a fine-tuning job.
abstract class OpenAIFineTuningCheckpointsBase {
  Future<OpenAIFineTuningCheckpointList> list({
    required String fineTuningJobId,
    String? after,
    int? limit,
    http.Client? client,
  });
}
